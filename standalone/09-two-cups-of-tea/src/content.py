def all_weeks():
    n = 0
    for s in SEASONS:
        for (theme, qs, together) in s["weeks"]:
            n += 1
            yield n, s, theme, qs, together

if __name__ == "__main__":
    ws = list(all_weeks())
    assert len(ws) == 52, len(ws)
    qs = [q for _, _, _, q3, _ in ws for q in q3]
    assert len(qs) == 156 and len(set(qs)) == 156, "duplicate question"
    themes = [t for _, _, t, _, _ in ws]; assert len(set(themes)) == 52, "duplicate theme"
    print("52 weeks, 156 unique questions, longest:", max(qs, key=len), len(max(qs, key=len)))
